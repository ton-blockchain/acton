/// Returns every known name for `method_id`.
///
/// Most IDs have exactly one name. ID `76_407` is shared by
/// `is_plugin_installed` and `version`.
#[must_use]
pub fn known_get_method_names(method_id: u64) -> &'static [(u64, &'static str)] {
    let start = KNOWN_GET_METHODS.partition_point(|(id, _)| *id < method_id);
    let end = KNOWN_GET_METHODS.partition_point(|(id, _)| *id <= method_id);
    &KNOWN_GET_METHODS[start..end]
}

/// Returns the first known name for `method_id`.
///
/// Use [`known_get_method_names`] when callers need to preserve collisions.
#[must_use]
pub fn known_get_method_name(method_id: u64) -> Option<&'static str> {
    known_get_method_names(method_id)
        .first()
        .map(|(_, name)| *name)
}
