package codegen

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"go/format"
	"go/token"
	"sort"
	"strconv"
	"strings"

	acton "github.com/ton-blockchain/acton/packages/abi-go"
)

const Header = "// Code generated by tolk-abi-to-go. DO NOT EDIT.\n"
const SnapshotFilename = "catalog.json"
const importPath = "github.com/ton-blockchain/acton/packages/abi-go"

type Options struct {
	Package   string
	SingleABI bool
	// Snapshot includes the exact catalog input as catalog.json in the output.
	Snapshot bool
}
type Diagnostic struct {
	ContractID string `json:"contract_id"`
	Root       string `json:"root"`
	Reason     string `json:"reason"`
}
type Output struct {
	Files       map[string][]byte
	Revision    string
	Diagnostics []Diagnostic
}
type CatalogInput struct {
	SchemaVersion int             `json:"schemaVersion"`
	Contracts     []ContractInput `json:"contracts"`
}
type ContractInput struct {
	ID             string          `json:"id"`
	DisplayName    string          `json:"displayName"`
	Hashes         []string        `json:"hashes"`
	KnownAddresses []string        `json:"knownAddresses"`
	Links          []acton.Link    `json:"links"`
	CompilerABI    json.RawMessage `json:"compilerAbi"`
}

// Generate returns deterministic formatted source files. Unsupported roots are
// retained as metadata with diagnostics; malformed ABI tables fail generation.
func Generate(data []byte, opts Options) (*Output, error) {
	if len(data) > 128<<20 {
		return nil, errors.New("input exceeds 128 MiB")
	}
	if opts.Snapshot && opts.SingleABI {
		return nil, errors.New("snapshot requires catalog input, not a single ABI")
	}
	if opts.Package == "" {
		opts.Package = "catalog"
	}
	if !token.IsIdentifier(opts.Package) || token.Lookup(opts.Package).IsKeyword() || opts.Package == "_" {
		return nil, errors.New("invalid Go package name")
	}
	digest := sha256.Sum256(data)
	out := &Output{Files: map[string][]byte{}, Revision: hex.EncodeToString(digest[:]), Diagnostics: []Diagnostic{}}
	var entries []ContractInput
	if opts.SingleABI {
		a, err := ParseABI(data)
		if err != nil {
			return nil, err
		}
		if a.Name == "" {
			return nil, errors.New("single ABI contract_name is empty")
		}
		entries = []ContractInput{{ID: a.Name, DisplayName: a.Name, CompilerABI: data}}
	} else {
		if err := require(data, "schemaVersion", "contracts"); err != nil {
			return nil, err
		}
		var raw map[string]json.RawMessage
		if err := json.Unmarshal(data, &raw); err != nil {
			return nil, err
		}
		if err := requiredArray(raw["contracts"], func(v json.RawMessage) error {
			if err := require(v, "id", "displayName", "hashes", "compilerAbi"); err != nil {
				return err
			}
			var fields map[string]json.RawMessage
			if err := json.Unmarshal(v, &fields); err != nil {
				return err
			}
			for _, name := range []string{"hashes", "knownAddresses"} {
				if value, ok := fields[name]; ok {
					if err := requiredArray(value, func(item json.RawMessage) error {
						if bytes.Equal(item, []byte("null")) {
							return errors.New("expected string, not null")
						}
						var text string
						return json.Unmarshal(item, &text)
					}); err != nil {
						return fmt.Errorf("%s: %w", name, err)
					}
				}
			}
			if links, ok := fields["links"]; ok {
				if err := requiredArray(links, func(link json.RawMessage) error { return require(link, "kind", "title", "url") }); err != nil {
					return fmt.Errorf("links: %w", err)
				}
			}
			return nil
		}); err != nil {
			return nil, err
		}
		var catalog CatalogInput
		if err := json.Unmarshal(data, &catalog); err != nil {
			return nil, err
		}
		if catalog.SchemaVersion != 1 {
			return nil, errors.New("unsupported catalog schemaVersion")
		}
		entries = catalog.Contracts
	}
	if len(entries) > 4096 {
		return nil, errors.New("catalog contract limit exceeded")
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].ID < entries[j].ID })
	seen, namespaces := map[string]bool{}, map[string]bool{}
	var registry strings.Builder
	fmt.Fprintf(&registry, "%s// Input SHA256: %s\npackage %s\nimport acton %q\nconst Revision = %q\nvar Contracts = []*acton.Contract{\n", Header, out.Revision, opts.Package, importPath, out.Revision)
	for _, entry := range entries {
		if entry.ID == "" || seen[entry.ID] {
			return nil, fmt.Errorf("empty or duplicate contract ID %q", entry.ID)
		}
		seen[entry.ID] = true
		if len(entry.ID) > 512 {
			return nil, errors.New("contract ID exceeds 512 bytes")
		}
		a, err := ParseABI(entry.CompilerABI)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", entry.ID, err)
		}
		hashSet := map[string]bool{}
		hashes := []string{}
		for _, h := range entry.Hashes {
			normalized, err := acton.NormalizeCodeHash(h)
			if err != nil {
				return nil, fmt.Errorf("%s hash: %w", entry.ID, err)
			}
			if !hashSet[normalized] {
				hashes = append(hashes, normalized)
				hashSet[normalized] = true
			}
		}
		sort.Strings(hashes)
		entry.Hashes = hashes
		idHash := sha256.Sum256([]byte(entry.ID))
		suffix := hex.EncodeToString(idHash[:8])
		ns := "C" + identifier(entry.ID) + "_" + suffix
		if namespaces[ns] {
			return nil, errors.New("contract namespace hash collision")
		}
		namespaces[ns] = true
		source, diagnostics, err := generateContract(a, entry, opts.Package, ns)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", entry.ID, err)
		}
		filename := "contract_" + suffix + "_gen.go"
		if out.Files[filename] != nil {
			return nil, errors.New("contract filename hash collision")
		}
		out.Files[filename] = source
		out.Diagnostics = append(out.Diagnostics, diagnostics...)
		fmt.Fprintf(&registry, "new%s(),\n", ns)
	}
	registry.WriteString(`}
var byID, byCodeHash = func() (map[string]*acton.Contract, map[string][]*acton.Contract) {
 ids := make(map[string]*acton.Contract, len(Contracts))
 hashes := make(map[string][]*acton.Contract)
 for _, c := range Contracts {
  ids[c.ID] = c
  for _, hash := range c.CodeHashes { hashes[hash] = append(hashes[hash], c) }
 }
 return ids, hashes
}()
func ByID(id string) *acton.Contract {
 return byID[id]
}
func ByCodeHash(hash string) []*acton.Contract {
 normalized, err := acton.NormalizeCodeHash(hash); if err != nil { return nil }
 return append([]*acton.Contract{}, byCodeHash[normalized]...)
}
`)
	formatted, err := format.Source([]byte(registry.String()))
	if err != nil {
		return nil, err
	}
	out.Files["registry_gen.go"] = formatted
	if opts.Snapshot {
		out.Files[SnapshotFilename] = bytes.Clone(data)
	}
	return out, nil
}

func identifier(s string) string {
	var b strings.Builder
	upper := true
	for _, c := range s {
		if c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9' {
			if b.Len() == 0 && c >= '0' && c <= '9' {
				b.WriteByte('X')
			}
			if upper && c >= 'a' && c <= 'z' {
				c -= 'a' - 'A'
			}
			b.WriteRune(c)
			upper = false
		} else {
			upper = true
		}
	}
	if b.Len() == 0 {
		return "Value"
	}
	return b.String()
}
func typeName(a *ABI, i int, ns string) string {
	t := a.Types[i]
	return fmt.Sprintf("%s%sT%d", ns, identifier(t.Struct+t.Enum+t.Alias), i)
}
func goType(a *ABI, i int, ns string, seen map[int]bool) string {
	if seen[i] || len(seen) > 128 {
		return "any"
	}
	seen[i] = true
	defer delete(seen, i)
	t := a.Types[i]
	switch t.Kind {
	case "int", "intN", "uintN", "varintN", "varuintN", "coins", "cell", "slice", "builder", "remaining", "string", "address":
		return "string"
	case "EnumRef":
		return typeName(a, i, ns)
	case "bool":
		return "bool"
	case "bitsN":
		return "acton.Bits"
	case "StructRef":
		return "*" + typeName(a, i, ns)
	case "AliasRef":
		return goType(a, a.targets[i], ns, seen)
	case "nullable":
		return "*" + goType(a, t.Inner, ns, seen)
	case "addressOpt":
		return "*string"
	case "cellOf":
		return goType(a, t.Inner, ns, seen)
	case "arrayOf", "lispListOf":
		return "[]" + goType(a, t.Inner, ns, seen)
	case "tensor", "shapedTuple":
		return "[]any"
	case "mapKV":
		return "[]acton.MapEntry"
	case "union":
		return "*acton.UnionValue"
	default:
		return "any"
	}
}
func typeInfo(a *ABI, i int) string {
	return fmt.Sprintf("acton.TypeInfo{Index:%d,Name:%q}", i, a.name(i))
}
func stringSlice(items []string) string {
	var b strings.Builder
	b.WriteString("[]string{")
	for _, s := range items {
		fmt.Fprintf(&b, "%q,", s)
	}
	b.WriteString("}")
	return b.String()
}
func codecRef(i int) string { return fmt.Sprintf("&codecs[%d]", i) }

func generateContract(a *ABI, entry ContractInput, pkg, ns string) ([]byte, []Diagnostic, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "%spackage %s\nimport (\"encoding/json\"; acton %q)\n", Header, pkg, importPath)
	for i, t := range a.Types {
		name := typeName(a, i, ns)
		switch t.Kind {
		case "StructRef":
			fmt.Fprintf(&b, "type %s struct {\n", name)
			for j, f := range a.fields[i] {
				idx := f.Index
				if f.Client != nil {
					idx = *f.Client
				}
				fmt.Fprintf(&b, "%sF%d %s %s\n", identifier(f.Name), j, goType(a, idx, ns, map[int]bool{}), strconv.Quote("json:"+strconv.Quote(f.Name)))
			}
			b.WriteString("}\n")
			// Getter structs can have a different shape than their client cell view.
			fmt.Fprintf(&b, "type %sStack struct {\n", name)
			for j, f := range a.fields[i] {
				fmt.Fprintf(&b, "%sF%d %s %s\n", identifier(f.Name), j, goStackType(a, f.Index, ns, map[int]bool{}), strconv.Quote("json:"+strconv.Quote(f.Name)))
			}
			b.WriteString("}\n")
		case "AliasRef":
			fmt.Fprintf(&b, "type %s = %s\n", name, goType(a, a.targets[i], ns, map[int]bool{i: true}))
		case "EnumRef":
			fmt.Fprintf(&b, "type %s string\n", name)
			seen := map[string]bool{}
			for j, m := range a.declaration(i).Members {
				if m.Name == "" || seen[m.Name] {
					return nil, nil, errors.New("duplicate/empty enum member")
				}
				seen[m.Name] = true
				x, err := acton.Integer(m.Value)
				if err != nil {
					return nil, nil, fmt.Errorf("enum %s: %w", name, err)
				}
				fmt.Fprintf(&b, "const %s%sM%d %s = %q\n", name, identifier(m.Name), j, name, x.String())
			}
		}
	}
	for i, m := range a.Methods {
		fmt.Fprintf(&b, "type %s%sG%dArgs struct {\n", ns, identifier(m.Name), i)
		for j, p := range m.Parameters {
			fmt.Fprintf(&b, "%sF%d %s %s\n", identifier(p.Name), j, goStackType(a, p.Index, ns, map[int]bool{}), strconv.Quote("json:"+strconv.Quote(p.Name)))
		}
		b.WriteString("}\n")
		fmt.Fprintf(&b, "type %s%sG%dResult = %s\n", ns, identifier(m.Name), i, goStackType(a, m.Return, ns, map[int]bool{}))
	}
	fmt.Fprintf(&b, "func new%s() *acton.Contract {\n", ns)
	if len(a.Types) != 0 {
		fmt.Fprintf(&b, "var codecs [%d]acton.Codec\n", len(a.Types))
	}
	for i := range a.Types {
		expr, err := codecExpr(a, i)
		if err != nil {
			return nil, nil, err
		}
		fmt.Fprintf(&b, "codecs[%d] = %s\n", i, expr)
	}
	compact := new(bytes.Buffer)
	if err := json.Compact(compact, entry.CompilerABI); err != nil {
		return nil, nil, err
	}
	fmt.Fprintf(&b, "c := &acton.Contract{ID:%q,DisplayName:%q,CodeHashes:%s,KnownAddresses:%s,ABI:json.RawMessage(%q),Links:[]acton.Link{", entry.ID, entry.DisplayName, stringSlice(entry.Hashes), stringSlice(entry.KnownAddresses), compact.String())
	for _, link := range entry.Links {
		fmt.Fprintf(&b, "{Kind:%q,Title:%q,URL:%q},", link.Kind, link.Title, link.URL)
	}
	b.WriteString("},GetMethods:[]acton.GetMethod{},Messages:map[string][]acton.Binding{}}\n")
	diagnostics := []Diagnostic{}
	binding := func(i int, root string) string {
		reason := a.support(i, false, map[string]bool{})
		if reason != "" {
			diagnostics = append(diagnostics, Diagnostic{ContractID: entry.ID, Root: root, Reason: reason})
		}
		return fmt.Sprintf("acton.NewBinding(%s,%s,%q)", typeInfo(a, i), codecRef(i), reason)
	}
	if a.Storage.Runtime != nil {
		fmt.Fprintf(&b, "c.Storage = %s\n", binding(*a.Storage.Runtime, "storage"))
	}
	if a.Storage.Deployment != nil {
		fmt.Fprintf(&b, "c.DeploymentStorage = %s\n", binding(*a.Storage.Deployment, "deployment_storage"))
	}
	for j, direction := range []string{"incoming_messages", "incoming_external", "outgoing_messages", "emitted_events"} {
		list := [][]Message{a.Incoming, a.External, a.Outgoing, a.Events}[j]
		fmt.Fprintf(&b, "c.Messages[%q] = []acton.Binding{\n", direction)
		for k, msg := range list {
			fmt.Fprintf(&b, "*%s,\n", binding(msg.Index, fmt.Sprintf("%s[%d]", direction, k)))
		}
		b.WriteString("}\n")
	}
	for _, m := range a.Methods {
		reason := a.support(m.Return, true, map[string]bool{})
		args := []string{}
		for _, p := range m.Parameters {
			r := a.support(p.Index, true, map[string]bool{})
			if reason == "" && r != "" {
				reason = p.Name + ": " + r
			}
			df, r := a.defaultFunc(p.Default, p.Index)
			if reason == "" && r != "" {
				reason = p.Name + " default: " + r
			}
			args = append(args, fmt.Sprintf("{Name:%q,Codec:%s,Default:%s}", p.Name, codecRef(p.Index), df))
		}
		if reason != "" {
			diagnostics = append(diagnostics, Diagnostic{ContractID: entry.ID, Root: "get_method:" + m.Name, Reason: reason})
		}
		fmt.Fprintf(&b, "c.GetMethods = append(c.GetMethods,acton.BindGetMethod(acton.GetMethod{Name:%q,ID:%d,Return:%s,Description:%q,Unsupported:%q,Parameters:[]acton.Parameter{", m.Name, m.ID, typeInfo(a, m.Return), m.Description, reason)
		for _, p := range m.Parameters {
			fmt.Fprintf(&b, "{Name:%q,Type:%s", p.Name, typeInfo(a, p.Index))
			if len(p.Default) != 0 {
				fmt.Fprintf(&b, ",Default:json.RawMessage(%q)", string(p.Default))
			}
			b.WriteString("},")
		}
		fmt.Fprintf(&b, "}},[]acton.Argument{%s},%s))\n", strings.Join(args, ","), codecRef(m.Return))
	}
	b.WriteString("return c\n}\n")
	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, nil, fmt.Errorf("format generated source: %w", err)
	}
	return formatted, diagnostics, nil
}

func goStackType(a *ABI, i int, ns string, seen map[int]bool) string {
	if seen[i] || len(seen) > 128 {
		return "any"
	}
	seen[i] = true
	defer delete(seen, i)
	t := a.Types[i]
	switch t.Kind {
	case "StructRef":
		return "*" + typeName(a, i, ns) + "Stack"
	case "AliasRef":
		return goStackType(a, a.targets[i], ns, seen)
	case "nullable":
		return "*" + goStackType(a, t.Inner, ns, seen)
	case "arrayOf", "lispListOf":
		return "[]" + goStackType(a, t.Inner, ns, seen)
	default:
		return goType(a, i, ns, map[int]bool{})
	}
}

func codecExpr(a *ABI, i int) (string, error) {
	t := a.Types[i]
	w, _ := a.width(i, map[int]bool{})
	switch t.Kind {
	case "int":
		return "acton.IntegerCodec(0,true,false)", nil
	case "intN", "uintN", "varintN", "varuintN":
		return fmt.Sprintf("acton.IntegerCodec(%d,%t,%t)", t.N, t.Kind == "intN" || t.Kind == "varintN", t.Kind == "varintN" || t.Kind == "varuintN"), nil
	case "coins":
		return "acton.IntegerCodec(16,false,true)", nil
	case "bool":
		return "acton.BoolCodec()", nil
	case "cell":
		return "acton.RawCellCodec()", nil
	case "string":
		return "acton.StringCodec()", nil
	case "slice", "remaining":
		return "acton.RemainderCodec(\"slice\")", nil
	case "builder":
		return "acton.RemainderCodec(\"builder\")", nil
	case "address", "addressOpt", "addressExt", "addressAny":
		return fmt.Sprintf("acton.AddressCodec(%q)", t.Kind), nil
	case "bitsN":
		return fmt.Sprintf("acton.BitsCodec(%d)", t.N), nil
	case "nullLiteral", "void":
		return fmt.Sprintf("acton.UnitCodec(%t)", t.Kind == "nullLiteral"), nil
	case "nullable":
		id := -1
		if t.TypeID != nil {
			id = *t.TypeID
		}
		return fmt.Sprintf("acton.NullableCodec(%s,%d,%d)", codecRef(t.Inner), w, id), nil
	case "cellOf":
		return fmt.Sprintf("acton.CellOfCodec(%s)", codecRef(t.Inner)), nil
	case "arrayOf", "lispListOf":
		b, r, _ := a.size(t.Inner, map[int]bool{})
		chunk := 255
		if b > 0 {
			chunk = min(chunk, 1022/b)
		}
		if r > 0 {
			chunk = min(chunk, 3/r)
		}
		chunk = max(1, chunk)
		return fmt.Sprintf("acton.ArrayCodec(%s,%d,%t)", codecRef(t.Inner), chunk, t.Kind == "lispListOf"), nil
	case "mapKV":
		b, _, _ := a.size(t.Key, map[int]bool{})
		return fmt.Sprintf("acton.MapCodec(%s,%s,%d)", codecRef(t.Key), codecRef(t.Value), min(b, 1023)), nil
	case "AliasRef":
		return fmt.Sprintf("acton.AliasCodec(%s,%d)", codecRef(a.targets[i]), w), nil
	case "EnumRef":
		members := []string{}
		for _, m := range a.declaration(i).Members {
			x, err := acton.Integer(m.Value)
			if err != nil {
				return "", err
			}
			members = append(members, x.String())
		}
		return fmt.Sprintf("acton.EnumCodec(%s,%s)", codecRef(a.declaration(i).Encoded), stringSlice(members)), nil
	case "tensor", "shapedTuple":
		items := []string{}
		for _, idx := range t.Items {
			items = append(items, codecRef(idx))
		}
		return fmt.Sprintf("acton.TupleCodec([]*acton.Codec{%s},%t,%d)", strings.Join(items, ","), t.Kind == "shapedTuple", w), nil
	case "StructRef":
		prefix := "nil"
		if p := a.declaration(i).Prefix; p != nil {
			prefix = fmt.Sprintf("&acton.Prefix{Value:%d,Bits:%d}", p.Num, p.Len)
		}
		fields := []string{}
		for _, f := range a.fields[i] {
			idx := f.Index
			if f.Client != nil {
				idx = *f.Client
			}
			df, _ := a.defaultFunc(f.Default, f.Index)
			fields = append(fields, fmt.Sprintf("{Name:%q,Cell:%s,Stack:%s,Default:%s}", f.Name, codecRef(idx), codecRef(f.Index), df))
		}
		return fmt.Sprintf("acton.StructCodec(%s,[]acton.Field{%s},%d)", prefix, strings.Join(fields, ","), w), nil
	case "union":
		variants := []string{}
		for _, v := range t.Variants {
			vw, _ := a.width(v.Index, map[int]bool{})
			if v.Width != nil {
				vw = *v.Width
			}
			id := -1
			if v.TypeID != nil {
				id = *v.TypeID
			}
			variants = append(variants, fmt.Sprintf("{Label:%q,Codec:%s,Prefix:acton.Prefix{Value:%d,Bits:%d},Implicit:%t,Null:%t,Void:%t,TypeID:%d,Width:%d}", a.name(v.Index), codecRef(v.Index), v.Num, v.Len, a.implicit(v), a.Types[v.Index].Kind == "nullLiteral", a.Types[v.Index].Kind == "void", id, vw))
		}
		return fmt.Sprintf("acton.UnionCodec([]acton.Variant{%s},%d)", strings.Join(variants, ","), w), nil
	default:
		return fmt.Sprintf("acton.UnsupportedCodec(%q)", "unsupported type "+a.name(i)), nil
	}
}
