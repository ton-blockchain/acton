import { readFileSync, writeFileSync } from "node:fs";
import semver from "semver";

const packageJsonPath = new URL("../package.json", import.meta.url);
const registryPath = new URL("../languages/registry.mjs", import.meta.url);
const emscriptenNodeFsPatchPath = new URL("./patch-emscripten-node-fs.mjs", import.meta.url);

const packageJson = JSON.parse(readFileSync(packageJsonPath, "utf8"));
const dependencyNames = Object.keys(packageJson.dependencies);

const languages = [
  {
    name: "func",
    exportName: "FUNC",
    functionName: "Func",
    runtimePath: "dist/funcfiftlib.js",
    emscriptenNodeFsPatchRange: ">=0.4.5 <=0.4.6",
  },
  {
    name: "tact",
    exportName: "TACT",
    functionName: "Tact",
    runtimePath: "dist/func/funcfiftlib.js",
    emscriptenNodeFsPatchRange: ">=1.0.0 <=1.6.13",
  },
  {
    name: "tolk",
    exportName: "TOLK",
    functionName: "Tolk",
    runtimePath: "dist/tolkfiftlib.js",
    emscriptenNodeFsPatchRange: ">=0.6.0 <=1.2.0",
  },
].map((language) => ({
  ...language,
  versions: dependencyNames
    .filter((dependencyName) => dependencyName.startsWith(`${language.name}-`))
    .map((dependencyName) => dependencyName.slice(language.name.length + 1))
    .reverse(),
}));

const sections = [
  "// Generated by scripts/generate-registry.mjs. Do not edit.",
  ...languages.map(renderSupportedVersions),
  ...languages.map(renderLoaders),
  ...languages.map(renderImporter),
  `async function importSupported(language, version, loaders, supportedVersions) {
  const loader = loaders[version];
  if (!loader) {
    throw new Error(
      \`unsupported \${language} compiler_version: \${version}; supported versions: \${supportedVersions.join(", ")}\`,
    );
  }

  return loader();
}`,
];

writeFileSync(registryPath, `${sections.join("\n\n")}\n`);
writeFileSync(emscriptenNodeFsPatchPath, renderEmscriptenNodeFsPatch());

function renderSupportedVersions(language) {
  const versions = language.versions.map((version) => `  ${JSON.stringify(version)},`).join("\n");
  return `export const SUPPORTED_${language.exportName}_VERSIONS = [\n${versions}\n];`;
}

function renderLoaders(language) {
  const loaders = language.versions
    .map(
      (version) =>
        `  ${JSON.stringify(version)}: () => import(${JSON.stringify(`${language.name}-${version}`)}),`,
    )
    .join("\n");
  return `const ${language.name}Loaders = {\n${loaders}\n};`;
}

function renderImporter(language) {
  return `export async function import${language.functionName}(version) {
  return importSupported(${JSON.stringify(language.name)}, version, ${language.name}Loaders, SUPPORTED_${language.exportName}_VERSIONS);
}`;
}

function renderEmscriptenNodeFsPatch() {
  const runtimePaths = languages
    .flatMap((language) =>
      language.versions
        .filter((version) =>
          semver.satisfies(version, language.emscriptenNodeFsPatchRange, {
            includePrerelease: true,
          }),
        )
        .map((version) => `${language.name}-${version}/${language.runtimePath}`),
    )
    .map((runtimePath) => `  ${JSON.stringify(runtimePath)},`)
    .join("\n");

  return `// Generated by scripts/generate-registry.mjs. Do not edit.

import { readFileSync, writeFileSync } from "node:fs";

const nodeModulesUrl = new URL("../node_modules/", import.meta.url);
const compilerRuntimePaths = [
${runtimePaths}
];

for (const runtimePath of compilerRuntimePaths) {
  const runtimeUrl = new URL(runtimePath, nodeModulesUrl);
  const current = readFileSync(runtimeUrl, "utf8");
  const patched = current
    .replaceAll('process["binding"]("constants")', 'require("node:fs").constants')
    .replaceAll('process.binding("constants")', 'require("node:fs").constants');

  if (patched !== current) {
    writeFileSync(runtimeUrl, patched);
  }
}
`;
}
