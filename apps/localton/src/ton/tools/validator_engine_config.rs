//! Typed model of `validator-engine`'s generated `config.json`.
//!
//! The engine owns the file, while Localton owns a small set of deliberate changes:
//! its outbound port, authenticated control endpoint, and optional liteserver. A
//! complete model prevents those changes from becoming recursive string-key edits
//! over arbitrary JSON and makes an incompatible TON release fail during bootstrap.

use std::{fs, path::Path};

use anyhow::{Context, Result};
use serde::{Deserialize, Serialize};

use crate::storage::write_json_atomic;

use super::types::{Ed25519PublicKey, KeyId, TonPublicKey};

const CONTROL_PERMISSIONS: i32 = 15;

/// Complete validator-engine configuration generated by the pinned TON release.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub(crate) struct ValidatorEngineConfig {
    #[serde(rename = "@type")]
    constructor: ValidatorConfigConstructor,
    out_port: u16,
    addrs: Vec<EngineAddress>,
    adnl: Vec<EngineAdnl>,
    dht: Vec<EngineDht>,
    validators: Vec<EngineValidator>,
    #[serde(default)]
    collators: Vec<EngineValidator>,
    fullnode: KeyId,
    fullnodeslaves: Vec<FullNodeSlave>,
    fullnodemasters: Vec<FullNodeMaster>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    fullnodeconfig: Option<FullNodeConfig>,
    liteservers: Vec<EngineLiteserver>,
    control: Vec<EngineControlInterface>,
    #[serde(default)]
    shards_to_monitor: Vec<i64>,
    gc: EngineGc,
}

impl ValidatorEngineConfig {
    /// Reads a generated config and rejects missing, unknown, or mistyped fields.
    pub(crate) fn load(path: &Path) -> Result<Self> {
        let bytes = fs::read(path)
            .with_context(|| format!("failed to read validator config {}", path.display()))?;
        serde_json::from_slice(&bytes)
            .with_context(|| format!("invalid validator config {}", path.display()))
    }

    /// Persists one validated config through the state directory's atomic writer.
    pub(crate) fn save(&self, path: &Path) -> Result<()> {
        write_json_atomic(path, self)
            .with_context(|| format!("failed to write validator config {}", path.display()))
    }

    /// Replaces the engine's generated outbound ADNL port with the node-owned port.
    pub(crate) fn set_out_port(&mut self, port: u16) {
        self.out_port = port;
    }

    /// Installs the independent identities used for administration and lite queries.
    ///
    /// TON's JSON schema stores these ports as integers. Keeping construction here
    /// prevents callers from accidentally serializing a CLI-oriented string value.
    pub(crate) fn set_local_services(
        &mut self,
        console_port: u16,
        control_server: TonPublicKey,
        control_client: TonPublicKey,
        liteserver: Option<(u16, TonPublicKey)>,
    ) {
        self.control = vec![EngineControlInterface {
            constructor: ControlInterfaceConstructor::Interface,
            id: control_server,
            port: console_port,
            allowed: vec![EngineControlProcess {
                constructor: ControlProcessConstructor::Process,
                id: control_client,
                permissions: CONTROL_PERMISSIONS,
            }],
        }];
        self.liteservers = liteserver
            .map(|(port, id)| EngineLiteserver {
                constructor: LiteserverConstructor::Liteserver,
                id,
                port,
            })
            .into_iter()
            .collect();
    }

    /// Returns keys already registered for an election round, if present.
    pub(crate) fn election_keys(&self, election_id: u32) -> Result<Option<ValidatorElectionKeys>> {
        self.validators
            .iter()
            .find(|validator| validator.election_date == election_id)
            .map(|validator| {
                let adnl = validator
                    .adnl_addrs
                    .first()
                    .context("existing election validator has no ADNL address")?;
                Ok(ValidatorElectionKeys {
                    signing_key: validator.id,
                    adnl: adnl.id,
                    election_end: validator.expire_at,
                })
            })
            .transpose()
    }

    /// Returns the public identity accepted by the local control interface.
    pub(crate) fn control_public_key(&self) -> Option<TonPublicKey> {
        self.control.first().map(|control| control.id)
    }

    /// Returns the public identity exposed by the configured liteserver.
    pub(crate) fn liteserver_public_key(&self) -> Option<TonPublicKey> {
        self.liteservers.first().map(|liteserver| liteserver.id)
    }

    /// Returns the ADNL identifier used by the engine's full-node role.
    pub(crate) const fn fullnode_adnl(&self) -> KeyId {
        self.fullnode
    }
}

/// Engine-owned keys that let election automation resume after a restart.
