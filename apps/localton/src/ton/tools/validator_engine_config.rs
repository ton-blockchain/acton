/// Converts the advertised IPv4 endpoint into the signed TL integer convention.
#[cfg(test)]
fn ton_ipv4(ip: std::net::Ipv4Addr) -> i32 {
    i32::from_be_bytes(ip.octets())
}

#[cfg(test)]
mod tests {
    use std::net::Ipv4Addr;

    use base64::{Engine, engine::general_purpose::STANDARD as BASE64};

    use super::*;

    fn config_json() -> serde_json::Value {
        let id = BASE64.encode([1_u8; 32]);
        serde_json::json!({
            "@type": "engine.validator.config",
            "out_port": 3272,
            "addrs": [{
                "@type": "engine.addr",
                "ip": ton_ipv4(Ipv4Addr::LOCALHOST),
                "port": 4442,
                "categories": [0, 1, 2, 3],
                "priority_categories": [],
            }],
            "adnl": [],
            "dht": [],
            "validators": [],
            "collators": [],
            "fullnode": id,
            "fullnodeslaves": [],
            "fullnodemasters": [],
            "liteservers": [],
            "control": [],
            "shards_to_monitor": [],
            "gc": { "@type": "engine.gc", "ids": [] },
        })
    }

    #[test]
    fn service_configuration_uses_numeric_ports_and_typed_ids() {
        let mut config: ValidatorEngineConfig = serde_json::from_value(config_json()).unwrap();
        config.set_local_services(
            4441,
            TonPublicKey::from_bytes([2; 32]),
            TonPublicKey::from_bytes([3; 32]),
            Some((18_004, TonPublicKey::from_bytes([4; 32]))),
        );
        let value = serde_json::to_value(config).unwrap();

        assert_eq!(value["control"][0]["port"], 4441);
        assert_eq!(value["control"][0]["allowed"][0]["permissions"], 15);
        assert_eq!(value["liteservers"][0]["port"], 18_004);
        assert!(value["liteservers"][0]["port"].is_number());
    }
}
